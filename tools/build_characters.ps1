#requires -Version 7.0
# Rebuilds character assets from their text definitions, configures Godot imports,
# and keeps docs/license_ledger.csv synchronized with character and animation assets.
param(
    [string]$Id,
    [switch]$All,
    [switch]$LedgerOnly
)
$ErrorActionPreference = "Stop"
. "$PSScriptRoot/blender_path.ps1"
. "$PSScriptRoot/godot_path.ps1"

$Ledger = Join-Path $RepoRoot "docs/license_ledger.csv"
$CharRoot = Join-Path $RepoRoot "assets/characters"
$AnimRoot = Join-Path $RepoRoot "assets/animations"

function Format-CsvRow($values) {
    return ($values | ForEach-Object {
        $val = "$_"
        if ($val -match '[,\r\n"]') {
            '"' + ($val -replace '"', '""') + '"'
        } else {
            $val
        }
    }) -join ","
}

function Sync-CharacterLedger {
    $today = Get-Date -Format "yyyy-MM-dd"
    $lines = [System.Collections.Generic.List[string]]::new()
    if (Test-Path $Ledger) {
        foreach ($line in [System.IO.File]::ReadAllLines($Ledger)) {
            if (-not ($line.StartsWith("chr_") -or $line.StartsWith("anm_"))) {
                $lines.Add($line)
            }
        }
    }

    if (Test-Path $CharRoot) {
        $charFiles = Get-ChildItem -LiteralPath $CharRoot -Recurse -File -Force | Sort-Object FullName
        foreach ($file in $charFiles) {
            $rel = [System.IO.Path]::GetRelativePath($RepoRoot, $file.FullName).Replace("\", "/")
            $id = "chr_" + ($file.Name -replace '\.', '_').ToLowerInvariant()
            if ($file.Name.EndsWith(".build.json")) {
                $lines.Add((Format-CsvRow @($id, "res://$rel", "", "Chronicle of Two project", "Original work", "", $file.Name, "", "", $today)))
            } else {
                $lines.Add((Format-CsvRow @(
                    $id, "res://$rel", "https://static.makehumancommunity.org/mpfb.html",
                    "MakeHuman Community and the Chronicle of Two project", "CC0",
                    "MPFB 2.0.18, makehuman_system_assets", $file.Name, "",
                    "Body, skin and hair from MakeHuman core assets; outfit, headgear and weapons generated by tools/characters (original work)",
                    $today
                )))
            }
        }
    }

    if (Test-Path $AnimRoot) {
        $animFiles = Get-ChildItem -LiteralPath $AnimRoot -Recurse -File -Force | Sort-Object FullName
        foreach ($file in $animFiles) {
            $rel = [System.IO.Path]::GetRelativePath($RepoRoot, $file.FullName).Replace("\", "/")
            $id = "anm_" + ($file.Name -replace '\.', '_').ToLowerInvariant()
            if ($rel -match 'assets/animations/quaternius/') {
                $sourceUrl = if ($file.Name -match 'UAL2') {
                    "https://quaternius.itch.io/universal-animation-library-2"
                } else {
                    "https://quaternius.itch.io/universal-animation-library"
                }
                $lines.Add((Format-CsvRow @(
                    $id, "res://$rel", $sourceUrl, "Quaternius", "CC0",
                    "Standard", $file.Name, "", "Unchanged", $today
                )))
            } elseif ($rel -match 'assets/animations/chronicle/') {
                $lines.Add((Format-CsvRow @(
                    $id, "res://$rel", "https://quaternius.itch.io/universal-animation-library",
                    "Quaternius and the Chronicle of Two project", "CC0",
                    "Standard", $file.Name, "",
                    "Slices, sequences and held poses built by tools/characters/godot/build_clips.gd",
                    $today
                )))
            }
        }
    }

    [System.IO.File]::WriteAllLines($Ledger, $lines)
    Write-Host "Ledger updated with character and animation assets."
}

if ($LedgerOnly) {
    Sync-CharacterLedger
    exit 0
}

if ($All -eq [bool]$Id) { throw "Choose exactly one of -Id <character> or -All." }

$definitions = if ($All) {
    @(Get-ChildItem -LiteralPath (Join-Path $RepoRoot "art/characters") -Filter "*.json" |
        Where-Object { $_.Name -ne "clips_extra.json" })
} else {
    if ($Id -notmatch '^[a-z][a-z0-9_]*$') { throw "Character Id must be a stable lower-case content ID." }
    @(Get-Item -LiteralPath (Join-Path $RepoRoot "art/characters/$Id.json"))
}

foreach ($definition in $definitions) {
    $outputPath = Join-Path $RepoRoot "assets/characters/$($definition.BaseName)"
    & $Blender --background --python-exit-code 1 --python (Join-Path $RepoRoot "tools/characters/blender/build.py") -- $definition.FullName $outputPath
    if ($LASTEXITCODE -ne 0) { throw "Character build failed for $($definition.BaseName) (exit $LASTEXITCODE)." }
}

Write-Host "Configuring Godot imports..."
& $Godot --headless --path $RepoRoot -s res://tools/characters/godot/write_imports.gd
if ($LASTEXITCODE -ne 0) { throw "write_imports.gd failed with exit code $LASTEXITCODE." }

Write-Host "Importing assets in Godot..."
$importOutput = & $Godot --headless --path $RepoRoot --import 2>&1
$importExit = $LASTEXITCODE
foreach ($outLine in $importOutput) {
    Write-Host $outLine
    if ($outLine -match 'ERROR:.*assets/(characters|animations)') {
        throw "Godot import reported error for character/animation assets: $outLine"
    }
}
if ($importExit -ne 0) {
    throw "Godot import failed with exit code $importExit."
}

Write-Host "Building extra animation clips..."
& $Godot --headless --path $RepoRoot -s res://tools/characters/godot/build_clips.gd
if ($LASTEXITCODE -ne 0) { throw "build_clips.gd failed with exit code $LASTEXITCODE." }

Sync-CharacterLedger
